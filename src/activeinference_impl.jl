"""
    activeinference_impl.jl - Implementation using ActiveInference.jl package

This provides an alternative implementation of the spider phobia model
using the ActiveInference.jl package for proper variational message passing.
"""

# Check if ActiveInference.jl is available
const ACTIVEINFERENCE_AVAILABLE = try
    @eval using ActiveInference
    true
catch e
    @warn "ActiveInference.jl not available: $e"
    false
end

"""
    build_aif_matrices(; params::ModelParams = ModelParams())

Build the A, B, C, D, E matrices in the format expected by ActiveInference.jl.
Returns matrices as Arrays (not vectors of arrays).
"""
function build_aif_matrices(; params::ModelParams = ModelParams())
    # Use ActiveInference.jl's create_matrix_templates for correct types
    # Our model: 3 state factors, 4 observation modalities
    n_states = [6, 2, 2]        # behavior, spider, danger
    n_observations = [2, 2, 3, 6]  # visual, arousal, affect, behavior
    n_controls = [2, 1, 1]      # approach/avoid for factor 1, no control for 2,3
    policy_len = params.T - 1   # T-1 timesteps of planning

    # Create templates with correct types
    A, B, C, D, E = ActiveInference.create_matrix_templates(
        n_states, n_observations, n_controls, policy_len, "zeros"
    )

    # Now populate the matrices using our model's values
    model = build_model(params = params)

    # Copy A matrices (observation likelihood)
    for g in 1:length(model.A)
        A[g] .= model.A[g]
    end

    # Copy B matrices (transitions)
    for f in 1:length(model.B)
        B[f] .= model.B[f]
    end

    # Copy C (preferences) - just first timestep
    for g in 1:length(model.C)
        C[g] .= model.C[g][:, 1]
    end

    # Copy D (initial state priors)
    for f in 1:length(model.D)
        D[f] .= model.D[f]
    end

    # E is generated by create_matrix_templates, make it uniform
    E .= 1.0 / length(E)

    # Create pA (Dirichlet priors for A) - same structure as A
    pA = deepcopy(A)
    for g in 1:length(model.a)
        pA[g] .= model.a[g]
    end

    # Create pD (Dirichlet priors for D)
    pD = deepcopy(D)
    for f in 1:length(model.d)
        pD[f] .= model.d[f]
    end

    return (
        A = A,
        B = B,
        C = C,
        D = D,
        E = E,
        pA = pA,
        pD = pD,
        Ns = n_states,
        No = n_observations,
        T = params.T,
        params = params
    )
end

"""
    run_aif_exposure_therapy(; n_trials=200, spider_dangerous=false, params=ModelParams(), low_concentration=false)

Run exposure therapy simulation using ActiveInference.jl package.

If low_concentration=true, uses weaker priors to demonstrate faster learning dynamics.
"""
function run_aif_exposure_therapy(;
    n_trials::Int = 200,
    spider_dangerous::Bool = false,
    params::ModelParams = ModelParams(),
    low_concentration::Bool = false
)
    if !ACTIVEINFERENCE_AVAILABLE
        error("ActiveInference.jl is required. Install with: using Pkg; Pkg.add(url=\"https://github.com/ilabcode/ActiveInference.jl\")")
    end

    # Build matrices
    matrices = build_aif_matrices(params = params)

    # Settings matching the paper
    settings = Dict(
        "policy_len" => matrices.T - 1,
        "use_utility" => true,
        "use_states_info_gain" => true,
        "use_param_info_gain" => true,
        "action_selection" => "stochastic",
        "modalities_to_learn" => [3],  # Learn affective consequences
        "factors_to_learn" => [3],      # Learn about danger
        "FPI_num_iter" => 16,
        "FPI_dF_tol" => 0.001
    )

    # Parameters matching the paper
    parameters = Dict(
        "gamma" => 1.0,   # Policy precision (paper: beta = 1)
        "alpha" => 4.0,   # Action precision (paper: alpha = 4)
        "lr_pA" => 1.0,   # Learning rate for A
        "lr_pD" => 1.0    # Learning rate for D
    )

    # For exposure mode, strongly bias E toward approach policies
    # Policies from create_matrix_templates: 8 policies as 3x3 matrices
    # Each policy[t, f] gives action for timestep t, factor f
    # We want policies that approach (action=1) at timestep 1, factor 1
    # That's policies where first_column[1] == 1, i.e., policies 1, 3, 5, 7
    E_biased = copy(matrices.E)
    approach_at_t1 = [1, 3, 5, 7]  # Policies with approach at t=1
    avoid_at_t1 = [2, 4, 6, 8]      # Policies with avoid at t=1
    # Heavily bias toward approach at first timestep
    E_biased[approach_at_t1] .= 0.99 / length(approach_at_t1)
    E_biased[avoid_at_t1] .= 0.01 / length(avoid_at_t1)
    E_biased = E_biased ./ sum(E_biased)

    # Optionally use lower concentration parameters for faster learning
    pD_init = if low_concentration
        pD_low = deepcopy(matrices.pD)
        # Use much weaker priors: [0.9, 0.1] instead of [45, 5]
        pD_low[3] = [1 - params.Psafe, params.Psafe]  # [0.9, 0.1] with Psafe=0.1
        pD_low
    else
        matrices.pD
    end

    # Initialize agent
    aif_agent = ActiveInference.init_aif(
        matrices.A, matrices.B,
        C = matrices.C,
        D = matrices.D,
        E = E_biased,
        pA = matrices.pA,
        pD = pD_init,
        settings = settings,
        parameters = parameters,
        verbose = false
    )

    @info "AIF agent created with $(length(aif_agent.E)) policies"
    @info "Initial pD[3]: $(aif_agent.pD[3])"

    # Track evolution
    d_evolution = Vector{Vector{Float64}}[]
    a_evolution = []
    approach_count = 0
    avoid_count = 0

    # Ground truth state
    danger_state = spider_dangerous ? 1 : 2

    for trial in 1:n_trials
        # Reset to initial state for each trial
        true_state = [1, 2, danger_state]  # start, spider present, danger status

        # Reset agent's beliefs for new trial (like starting a fresh episode)
        # Only reset qs_current, don't reset prior - this allows pD learning to accumulate
        for f in 1:length(matrices.Ns)
            # Start from pD-derived prior each trial
            aif_agent.qs_current[f] .= aif_agent.pD[f] ./ sum(aif_agent.pD[f])
        end

        # Run one trial (T timesteps)
        for t in 1:matrices.T
            # Generate observation from true state
            obs = sample_observation_aif(matrices, true_state)

            # ActiveInference.jl inference loop
            ActiveInference.infer_states!(aif_agent, obs)
            ActiveInference.update_parameters!(aif_agent)
            ActiveInference.infer_policies!(aif_agent)

            if t < matrices.T
                action_raw = ActiveInference.sample_action!(aif_agent)
                # Convert to Vector{Int} - ActiveInference.jl returns Real[]
                action = Int.(action_raw)

                # EXPOSURE MODE: Force approach (action 1) on factor 1 at t=1
                # This simulates the therapist requiring the patient to approach
                if t == 1
                    action[1] = 1  # Force approach
                    approach_count += 1
                else
                    # Track natural behavior at later timesteps
                    if action[1] == 1
                        # approach at t>1
                    end
                end

                # Transition state
                true_state = transition_state_aif(matrices, true_state, action)
            end
        end

        # Store belief evolution
        push!(d_evolution, [copy(aif_agent.pD[f]) for f in 1:length(matrices.D)])
        push!(a_evolution, copy(aif_agent.pA[3]))

        if trial % 50 == 0
            @info "AIF Trial $trial/$n_trials: Approach=$approach_count, Avoid=$avoid_count"
            @info "  pD[3]=$(aif_agent.pD[3]), pA[3] sum=$(sum(aif_agent.pA[3]))"
        end
    end

    return (
        agent = aif_agent,
        d_evolution = d_evolution,
        a_evolution = a_evolution,
        approach_count = approach_count,
        avoid_count = avoid_count,
        n_trials = n_trials
    )
end

"""
    sample_observation_aif(matrices, state)

Sample observation given true state (for ActiveInference.jl version).
"""
function sample_observation_aif(matrices, state::Vector{Int})
    obs = Int[]
    for g in 1:length(matrices.No)
        A_g = matrices.A[g]
        probs = A_g[:, state...]
        probs = probs ./ (sum(probs) + 1e-16)

        # Sample from categorical
        r = rand()
        cumprob = 0.0
        sampled = 1
        for i in 1:length(probs)
            cumprob += probs[i]
            if r <= cumprob
                sampled = i
                break
            end
        end
        push!(obs, sampled)
    end
    return obs
end

"""
    transition_state_aif(matrices, state, action)

Apply state transition given action (for ActiveInference.jl version).
"""
function transition_state_aif(matrices, state::Vector{Int}, action::Vector{Int})
    new_state = similar(state)
    for f in 1:length(state)
        B_f = matrices.B[f]
        a = min(action[f], size(B_f, 3))
        trans_probs = B_f[:, state[f], a]
        trans_probs = trans_probs ./ (sum(trans_probs) + 1e-16)

        # Sample from categorical
        r = rand()
        cumprob = 0.0
        sampled = 1
        for i in 1:length(trans_probs)
            cumprob += trans_probs[i]
            if r <= cumprob
                sampled = i
                break
            end
        end
        new_state[f] = sampled
    end
    return new_state
end
